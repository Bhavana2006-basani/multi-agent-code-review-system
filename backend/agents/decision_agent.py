def run_decision_agent(ai_review_result):
    """
    Agent 04 - Decision Agent

    Compares the optimized code candidates generated by
    the AI Review Agent and selects the best candidate.

    Evaluation criteria:
    - Security
    - Readability
    - Maintainability
    - Reliability
    - Performance
    """

    # =====================================================
    # VALIDATE AI REVIEW RESULT
    # =====================================================

    if not ai_review_result:
        return {
            "success": False,
            "error": "AI Review result is missing."
        }

    if not ai_review_result.get("success"):
        return {
            "success": False,
            "error": "AI Review Agent did not complete successfully."
        }

    candidates = ai_review_result.get("candidates", [])

    if not candidates:
        return {
            "success": False,
            "error": "No optimized candidates were generated."
        }


    # =====================================================
    # WEIGHTS
    # =====================================================

    weights = {
        "security": 0.25,
        "readability": 0.20,
        "maintainability": 0.20,
        "reliability": 0.20,
        "performance": 0.15
    }


    evaluated_candidates = []


    # =====================================================
    # EVALUATE EACH CANDIDATE
    # =====================================================

    for candidate in candidates:

        scores = candidate.get(
            "estimated_scores",
            {}
        )

        security = scores.get("security", 0)
        readability = scores.get("readability", 0)
        maintainability = scores.get("maintainability", 0)
        reliability = scores.get("reliability", 0)
        performance = scores.get("performance", 0)


        # =================================================
        # WEIGHTED OVERALL SCORE
        # =================================================

        overall_score = (
            security * weights["security"]
            + readability * weights["readability"]
            + maintainability * weights["maintainability"]
            + reliability * weights["reliability"]
            + performance * weights["performance"]
        )


        evaluated_candidate = {
            "candidate_id": candidate.get("candidate_id"),
            "name": candidate.get("name"),
            "focus": candidate.get("focus"),

            "security": security,
            "readability": readability,
            "maintainability": maintainability,
            "reliability": reliability,
            "performance": performance,

            "time_complexity": candidate.get(
                "time_complexity",
                "Not available"
            ),

            "overall_score": round(
                overall_score,
                2
            )
        }


        evaluated_candidates.append(
            evaluated_candidate
        )


    # =====================================================
    # SELECT BEST CANDIDATE
    # =====================================================

    best_evaluation = max(
        evaluated_candidates,
        key=lambda item: item["overall_score"]
    )


    best_candidate = next(
        candidate
        for candidate in candidates
        if candidate.get("candidate_id")
        == best_evaluation["candidate_id"]
    )


    # =====================================================
    # GENERATE DECISION REASON
    # =====================================================

    decision_reason = (
        f"{best_candidate.get('name')} was selected because "
        f"it achieved the highest weighted overall score of "
        f"{best_evaluation['overall_score']}%. "
        f"The decision considers security, readability, "
        f"maintainability, reliability and performance."
    )


    # =====================================================
    # FINAL RESULT
    # =====================================================

    return {

        "success": True,

        "selected_candidate_id":
            best_candidate.get("candidate_id"),

        "selected_candidate_name":
            best_candidate.get("name"),

        "overall_score":
            best_evaluation["overall_score"],

        "time_complexity":
            best_candidate.get(
                "time_complexity",
                "Not available"
            ),

        "reason":
            decision_reason,

        "final_optimized_code":
            best_candidate.get(
                "optimized_code",
                ""
            ),

        "selected_scores":
            best_candidate.get(
                "estimated_scores",
                {}
            ),

        "candidate_comparison":
            evaluated_candidates,

        "weights":
            weights
    }